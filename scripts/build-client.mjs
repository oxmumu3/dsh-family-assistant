import { readFile, writeFile } from 'node:fs/promises';

// Browser plugin entries are classic __ModuleLoader__ contributions. Keep the
// testable microphone source separate, then assemble a closed lexical scope;
// there is no runtime eval, network dependency, or microphone code in the iframe.
const root = new URL('../', import.meta.url);
const [capture, entry] = await Promise.all(['src/voice-capture.mjs', 'src/client-entry.js'].map(name => readFile(new URL(name, root), 'utf8')));
if (/^import\s/m.test(capture)) throw new Error('Voice capture must stay browser-self-contained');
const source = `/* Generated by scripts/build-client.mjs; edit client-entry.js and voice-capture.mjs. */\n(() => {\n${capture.replace(/^export /gm, '')}\n${entry}\n})();\n`;
const target = new URL('src/client.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw new Error('Client bundle is stale; run node scripts/build-client.mjs');
} else await writeFile(target, source);
